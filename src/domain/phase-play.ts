import type { Phase } from "./phase";

/**
 * 一个阶段里，红蓝裁三方各自的那一节 —— **可派发的阶段各一份，各写各的**
 * （`Done` 是终点什么都不派；退休阶段的那几份冻着给历史）。
 *
 * ## 为什么不是一份模板加几个分支
 *
 * 骨架（红方产出、反方攻击、裁判裁决）是共用的，但**每个阶段的任务和定位有真实的
 * 区别**：设计阶段的反方不许读仓库，Build 的反方要能读改动文件和上游要求，
 * QA 的反方还得能自己跑。
 *
 * 这些差别原来挂在一个函数的 if 链上（`blueReach` 五分支）、一张前缀表上
 * （`ID_PREFIX`，只有 Review/QA 有），而**加一个阶段要回去改那些公共件，漏了也不会
 * 红**。用户 2026-08-03：「每个阶段都要重排，功能不变，但是不能再用同一个小基座了。」
 *
 * ## 重复是故意的
 *
 * 各份里有些句子一模一样 —— **不许提取公因子**。提取出来就是把那个模板悄悄请了
 * 回来，而下一次「只想改 Build 那一句」又会变成往公共件上挂分支。这张表存在的全部
 * 意义，就是让一个阶段可以独自变。
 *
 * `domain/round-prompt.golden.txt` 逐字节钉着每一份的产物：改一条记录，其余各条
 * 的快照必须纹丝不动。
 *
 * ## 这个模块是纯的，而且不 import 任何东西
 *
 * 只有文本和 `Phase` 这个类型。
 */
export interface PhasePlay {
  /** 正方那一节 —— 任务本身由调用方注入，这里是它周围的话。 */
  readonly red: {
    /** 抬头：转达要求。 */
    readonly heading: string;
    /** id 怎么起。**只有红方的发现也算数的阶段才有**（Review / QA）。 */
    readonly idRule: readonly string[];
  };
  /** 反方那一节。 */
  readonly blue: {
    /** 它这一阶段审什么。 */
    readonly task: string;
    /** 它够得着什么 —— 这是阶段之间差得最多的一项。 */
    readonly reach: string;
    /**
     * 反方在这一阶段是**去调查**，还是**对着标准评一份文档**。
     *
     * 判据紧跟着上面那行 `reach`，因为它就是 `reach` 的直接后果 —— 放在这儿而不是
     * 另建一张名单，是为了让「够得着代码」和「发现是无界的」永远是同一处的两行。
     *
     * - `true`（够得着代码：Build / Fix / Review / QA / Merge）——
     *   它自己去看，报出来的是**真缺陷**。那个空间无界是本质的，不是病：
     *   Review 砍掉它，就只剩红方一个人看代码，对抗价值当场归零。
     * - `false`（只读那份产出：PRD / Spec / TechSpec / Plan / TestPlan / Retro）——
     *   它的判断全部走逐条判定，**每轮上限 = criterion 条数，收敛 = 全 yes**。
     *   真库 CHG-001 那 139 条无界发现，全是从这半边来的。
     */
    readonly investigates: boolean;
    /** id 怎么起。红蓝共用 id 空间的阶段要分前缀，否则会静默丢一条。 */
    readonly idRule: readonly string[];
    /** 格式契约之后还要交代的话。 */
    readonly after: readonly string[];
  };
}

