import type { Phase } from "./phase";
import type { CriterionDraft, RubricRole } from "./rubric";

/**
 * 出厂自带的标准。**一条都不阻断。**
 *
 * ## 为什么全是 `blocking: false`
 *
 * `not_assessed` 是阻断的（标了阻断的漏答视同阻断）。所以出厂就勾上阻断，等于
 * **任何一次模型漏答都会立刻给每一个项目挂上一条挡门的东西** —— 而它的出口只有
 * 「进设置里把这条标准撤下来」。人会在完全不知道 rubric 是什么的情况下先被拦住。
 *
 * 默认是给人一个起点去读、去改、去决定哪几条值得挡，不是替他做那个决定。
 * 这条是 `RUBRIC-DESIGN.md` §3 末句，别在补默认条目时顺手把它翻掉。
 *
 * ## 为什么 critic 和 verdict 只有一套
 *
 * 它们讲的不是产物，是**方法**：怎么质疑一份东西、怎么裁一场争论。这两件事在
 * PRD 和在 Merge 是一样的。给每个阶段各抄一份只会得到十一份同样的话，然后它们
 * 开始各自漂移 —— 那正是「一个概念一个名字」要挡的。
 *
 * 只有 producer 是逐阶段的，因为「这个阶段该产出什么」逐阶段不同。
 *
 * ## 这些话是起点，不是权威
 *
 * 它们没有经过用户拍板。真正的权威是用户在面板上改出来的那一版 —— 这里只保证
 * 一个新项目不是从空白开始。
 *
 * ## 这个模块是纯的
 */

/** 怎么质疑。和阶段无关。 */
const CRITIC = [
  "每条问题都指向产出里的具体位置，而不是泛泛地说「不够清楚」",
  "每条问题都说明了它为什么是问题，而不只是说它存在",
  "没有提出需要读仓库或跑代码才能验证的问题 —— 只基于摆在面前的产出",
  "同一个问题在后续轮次沿用了同一个 id，没有换个说法重开一条",
];

/** 怎么裁。和阶段无关。 */
const VERDICT = [
  "对每一条已经存在的问题都明确表了态，没有沉默略过任何一条",
  "关闭任何一条时都写清楚了它为什么不再成立，而不是「已修复」四个字",
  "没有替正方复述或辩解 —— 裁决只针对问题本身",
  "没有把「这一轮没提到」当成「已经解决」",
];

/** 每个阶段该产出什么。**这一栏才是逐阶段不同的。** */
