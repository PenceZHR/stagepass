/**
 * 同上，裁判那一侧。
 *
 * Build 这一条防的是一个具体的失效：编码规范类的问题**天生看起来「不影响功能」**，
 * 而裁判手里正好有一个「判它不成立」的按钮。让它这么关掉，等于这四条标准写了也白写。
 *
 * **它的正确出口是人接受风险（waive），不是裁判判它不成立** —— 前者留在交付说明里，
 * 后者在库里什么都不留。
 */
const VERDICT_EXTRA: Partial<Readonly<Record<Phase, readonly string[]>>> = {
  Build: [
    "没有因为「不影响功能」就把编码规范类的问题关掉 —— 那类问题的出口是人接受风险，不是裁判判它不成立",
  ],
};

/**
 * 一个阶段、一个角色的出厂标准。
 *
 * 返回空数组是合法的，意思是这一栏没有出厂默认 —— 空 rubric 本来就合法，
 * 等于这个角色不做判定。
 */
export function defaultCriteria(phase: Phase, role: RubricRole): CriterionDraft[] {
  if (role === "producer") {
    return PRODUCER[phase].map((entry) => (typeof entry === "string"
      ? { text: entry, blocking: false, section: null }
      // **挂了节就出厂阻断。** 判据是结构性的，不是一张要维护的例外名单 ——
      // 名单会漂，「有没有挂节」不会。
      : { text: entry.text, blocking: true, section: entry.section }));
  }
  // 终局阶段（Done）没有 producer 标准，那就一栏都不给 —— 空 rubric 本来就合法。
  if (PRODUCER[phase].length === 0) return [];
  const texts = role === "critic"
    ? [
      ...CRITIC,
      // 按**这个阶段的反方到底有什么通道**拼，不按一张手维护的名单。
      ...(reportsFreeFormBlockers(phase) ? CRITIC_WITH_BLOCKERS : CRITIC_WITH_ASSESSMENTS),
      ...CRITIC_EXTRA[phase] ?? [],
    ]
    : [...VERDICT, ...VERDICT_EXTRA[phase] ?? []];
  // blocking 一律 false，理由见文件开头。**不要在这里开一个参数把它打开。**
  return texts.map((text) => ({ text, blocking: false, section: null }));
}
